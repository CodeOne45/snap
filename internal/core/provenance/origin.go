// Package provenance defines the .snap/origin.toml file written into every
// generated project: which template and version it came from and what
// variable values were used. It is deliberately a separate type from
// template.Manifest — a manifest defines variables, origin.toml records
// resolved values, and v2's "snap update" will read origin.toml heavily
// without caring about manifest schema changes.
package provenance

import (
	"fmt"
	"time"

	"github.com/BurntSushi/toml"
)

// File is the path (relative to a generated project's root) origin.toml is
// always written to.
const File = ".snap/origin.toml"

// Origin is the provenance recorded for one generated project.
type Origin struct {
	Template    string         `toml:"template,omitempty"`
	Version     string         `toml:"version,omitempty"`
	Source      string         `toml:"source,omitempty"` // "local" for the MVP local store; a git URL+commit in v1
	GeneratedAt time.Time      `toml:"generated_at,omitempty"`
	Variables   map[string]any `toml:"variables,omitempty"`
	// Toggles records every [[optional]] block's resolved on/off state
	// (not just the ones explicitly overridden), so a future "snap update"
	// (v2) can reproduce exactly what was generated. Omitted entirely for
	// a template with no optional blocks.
	Toggles map[string]bool `toml:"toggles,omitempty"`
	// Recipes records every recipe applied to this project (M20), oldest
	// first. A project not generated by Snap has an origin.toml with only
	// this field set — Template/Version/Source/GeneratedAt all empty/zero.
	Recipes []RecipeEntry `toml:"recipes,omitempty"`
}

// RecipeEntry is one applied recipe, recorded as a "[[recipes]]" entry.
type RecipeEntry struct {
	Name      string         `toml:"name"`
	Version   string         `toml:"version"`
	Source    string         `toml:"source"`
	AppliedAt time.Time      `toml:"applied_at"`
	Variables map[string]any `toml:"variables,omitempty"`
}

// TOML marshals o to its on-disk snap.toml-sibling format. GeneratedAt must
// be set whenever Template is (a zero time is rejected rather than
// silently writing 0001-01-01T00:00:00Z); likewise every recipe's
// AppliedAt.
func (o Origin) TOML() ([]byte, error) {
	if o.Template != "" && o.GeneratedAt.IsZero() {
		return nil, fmt.Errorf("provenance: origin: GeneratedAt must be set")
	}
	for _, r := range o.Recipes {
		if r.AppliedAt.IsZero() {
			return nil, fmt.Errorf("provenance: origin: recipe %q: AppliedAt must be set", r.Name)
		}
	}
	data, err := toml.Marshal(o)
	if err != nil {
		return nil, fmt.Errorf("provenance: marshal origin: %w", err)
	}
	return data, nil
}

// ParseOrigin parses a generated project's .snap/origin.toml, the inverse
// of Origin.TOML — used by M15's base regeneration to recover exactly what
// a project was originally generated from. A file with no [template] block
// is only valid when it carries at least one [[recipes]] entry (a project
// not generated by Snap that has had recipes applied to it since).
func ParseOrigin(data []byte) (Origin, error) {
	var o Origin
	if err := toml.Unmarshal(data, &o); err != nil {
		return Origin{}, fmt.Errorf("provenance: parse %s: %w", File, err)
	}
	if o.Template == "" && len(o.Recipes) == 0 {
		return Origin{}, fmt.Errorf("provenance: parse %s: template is required", File)
	}
	if o.Template != "" {
		if o.Version == "" {
			return Origin{}, fmt.Errorf("provenance: parse %s: version is required", File)
		}
		if o.GeneratedAt.IsZero() {
			return Origin{}, fmt.Errorf("provenance: parse %s: generated_at is required", File)
		}
	}
	for _, r := range o.Recipes {
		if r.Name == "" {
			return Origin{}, fmt.Errorf("provenance: parse %s: a recipe entry is missing a name", File)
		}
		if r.Version == "" {
			return Origin{}, fmt.Errorf("provenance: parse %s: recipe %q: version is required", File, r.Name)
		}
		if r.AppliedAt.IsZero() {
			return Origin{}, fmt.Errorf("provenance: parse %s: recipe %q: applied_at is required", File, r.Name)
		}
	}
	return o, nil
}
